def get_palette(theme_name):
    """Create a QPalette from theme colors."""
    from PyQt5.QtGui import QPalette, QColor
    t = THEMES.get(theme_name, THEMES["Axiom Dark"])
    p = QPalette()
    p.setColor(QPalette.Window, QColor(t["window"]))
    p.setColor(QPalette.WindowText, QColor(t["window_text"]))
    p.setColor(QPalette.Base, QColor(t["base"]))
    p.setColor(QPalette.AlternateBase, QColor(t["alt_base"]))
    p.setColor(QPalette.ToolTipBase, QColor(t["tooltip_bg"]))
    p.setColor(QPalette.ToolTipText, QColor(t["text"]))
    p.setColor(QPalette.Text, QColor(t["text"]))
    p.setColor(QPalette.Button, QColor(t["button"]))
    p.setColor(QPalette.ButtonText, QColor(t["button_text"]))
    p.setColor(QPalette.BrightText, QColor("#ff3333"))
    p.setColor(QPalette.Link, QColor(t["link"]))
    p.setColor(QPalette.Highlight, QColor(t["highlight"]))
    p.setColor(QPalette.HighlightedText, QColor(t["highlight_text"]))
    p.setColor(QPalette.Disabled, QPalette.Text, QColor(t["disabled_text"]))
    p.setColor(QPalette.Disabled, QPalette.ButtonText, QColor(t["disabled_text"]))
    return p
